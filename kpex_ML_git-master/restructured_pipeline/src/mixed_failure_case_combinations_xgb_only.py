# ============================================================================
# Load current enriched XGB failure sheets
# ============================================================================

def load_xgb_frames(
    failure_workbook: Path,
    split_mode: str,
) -> dict[str, pd.DataFrame]:

    if split_mode not in XGB_SHEETS_BY_SPLIT:
        raise ValueError(
            f"Unsupported split mode: {split_mode!r}. "
            f"Expected one of {SUPPORTED_SPLIT_MODES}."
        )

    frames: dict[str, pd.DataFrame] = {}

    for scheme_name, sheet_name in (
        XGB_SHEETS_BY_SPLIT[split_mode].items()
    ):

        print(
            f"Loading {scheme_name} / {split_mode}: "
            f"{sheet_name}"
        )

        df = pd.read_excel(
            failure_workbook,
            sheet_name=sheet_name,
        ).copy()

        required_columns = {
            "dataset",
            "k_value",
            "scheme",
            "model",
            "split_mode",
            "data_scope",
            "fastest_algo_rank",
            "fastest_algo_tuple",

            "top1_min_time_ratio",
            "top1_candidate",

            "top2_min_time_ratio",
            "top2_candidate",

            "top3_min_time_ratio",
            "top3_candidate",

            "top4_min_time_ratio",
            "top4_candidate",

            "top5_min_time_ratio",
            "top5_candidate",

            "top6_min_time_ratio",
            "top6_candidate",

            "all_predictions_sorted_by_prob",
        }

        missing = sorted(
            required_columns - set(df.columns)
        )

        if missing:
            raise ValueError(
                f"Missing required columns in "
                f"{sheet_name!r}: {missing}"
            )

        # -----------------------------------------------------
        # Validate provenance
        # -----------------------------------------------------

        invalid_scheme = ~df["scheme"].eq(
            scheme_name
        )

        if invalid_scheme.any():
            values = (
                df.loc[
                    invalid_scheme,
                    "scheme",
                ]
                .drop_duplicates()
                .tolist()
            )

            raise ValueError(
                f"{sheet_name!r} contains unexpected "
                f"scheme values: {values}"
            )

        invalid_model = ~df["model"].eq("XGB")

        if invalid_model.any():
            values = (
                df.loc[
                    invalid_model,
                    "model",
                ]
                .drop_duplicates()
                .tolist()
            )

            raise ValueError(
                f"{sheet_name!r} contains non-XGB "
                f"rows: {values}"
            )

        invalid_split = ~df["split_mode"].eq(
            split_mode
        )

        if invalid_split.any():
            values = (
                df.loc[
                    invalid_split,
                    "split_mode",
                ]
                .drop_duplicates()
                .tolist()
            )

            raise ValueError(
                f"{sheet_name!r} contains unexpected "
                f"split modes: {values}"
            )

        # -----------------------------------------------------
        # IMPORTANT:
        #
        # Use only entire_data here.
        #
        # test_data is a subset of entire_data and is used later
        # to determine train/test membership. Mixing both here
        # would duplicate the same failure observation.
        # -----------------------------------------------------

        before_scope_filter = len(df)

        df = df[
            df["data_scope"].eq("entire_data")
        ].copy()

        after_scope_filter = len(df)

        print(
            f"  rows before scope filter: "
            f"{before_scope_filter}"
        )

        print(
            f"  entire_data rows used:    "
            f"{after_scope_filter}"
        )

        if df.empty:
            print(
                f"WARNING: {sheet_name!r} contains no "
                f"entire_data XGB failures."
            )

        frames[scheme_name] = (
            df.reset_index(drop=True)
        )

    return frames


# ============================================================================
# Top-k rule helpers
# ============================================================================

def extract_topk_pair(
    sheet_name: str,
) -> tuple[str, str]:

    left_name, right_name = (
        sheet_name.split(
            "__",
            maxsplit=1,
        )
    )

    left_topk = left_name.split("_")[-1]
    right_topk = right_name.split("_")[-1]

    return left_topk, right_topk


def filter_frame_for_active_rule(
    frame: pd.DataFrame,
    topk_label: str,
) -> pd.DataFrame:

    ratio_column = (
        f"{topk_label}_min_time_ratio"
    )

    if ratio_column not in frame.columns:
        raise ValueError(
            f"Missing ratio column "
            f"{ratio_column!r}."
        )

    ratios = pd.to_numeric(
        frame[ratio_column],
        errors="coerce",
    )

    filtered = frame[
        ratios > MIN_RATIO_THRESHOLD
    ].copy()

    return filtered


# ============================================================================
# Build combination sheet
# ============================================================================

def build_sheet(
    left_df: pd.DataFrame,
    right_df: pd.DataFrame,
    source_rule: str,
) -> pd.DataFrame:

    left_topk, right_topk = (
        extract_topk_pair(source_rule)
    )

    filtered_left = (
        filter_frame_for_active_rule(
            left_df,
            left_topk,
        )
    )

    filtered_right = (
        filter_frame_for_active_rule(
            right_df,
            right_topk,
        )
    )

    combined = pd.concat(
        [
            filtered_left,
            filtered_right,
        ],
        ignore_index=True,
        sort=False,
    )

    combined["source_scheme"] = (
        combined["scheme"]
    )

    combined["source_rule"] = source_rule

    combined = combined[
        OUTPUT_COLUMNS
    ].copy()

    # ---------------------------------------------------------
    # Keep Scheme 1 / Scheme 3 rows adjacent for the same
    # dataset/K pair.
    # ---------------------------------------------------------

    combined = combined.sort_values(
        by=[
            "dataset",
            "k_value",
            "scheme",
        ],
        ascending=[
            True,
            True,
            True,
        ],
        kind="stable",
    ).reset_index(drop=True)

    return combined


# ============================================================================
# Workbook summary
# ============================================================================

def build_summary(
    sheet_frames: dict[str, pd.DataFrame],
    xgb_frames: dict[str, pd.DataFrame],
    split_mode: str,
) -> pd.DataFrame:

    rows = []

    for (
        left_scheme,
        right_scheme,
        sheet_name,
    ) in SHEET_SPECS:

        frame = sheet_frames[
            sheet_name
        ]

        left_topk, right_topk = (
            extract_topk_pair(sheet_name)
        )

        left_before = len(
            xgb_frames[left_scheme]
        )

        right_before = len(
            xgb_frames[right_scheme]
        )

        left_after = int(
            frame["source_scheme"]
            .eq(left_scheme)
            .sum()
        )

        right_after = int(
            frame["source_scheme"]
            .eq(right_scheme)
            .sum()
        )

        rows.append(
            {
                "sheet_name":
                    sheet_name,

                "split_mode":
                    split_mode,

                "scheme_pair":
                    f"{left_scheme} + "
                    f"{right_scheme}",

                "left_scheme":
                    left_scheme,

                "right_scheme":
                    right_scheme,

                "left_topk":
                    left_topk,

                "right_topk":
                    right_topk,

                "topk_pairing":
                    f"{left_topk} + "
                    f"{right_topk}",

                "left_rows_before_filter":
                    int(left_before),

                "left_rows_after_filter":
                    int(left_after),

                "right_rows_before_filter":
                    int(right_before),

                "right_rows_after_filter":
                    int(right_after),

                "rows_before_filter":
                    int(
                        left_before
                        + right_before
                    ),

                "rows_after_filter":
                    int(len(frame)),

                "rows_removed":
                    int(
                        left_before
                        + right_before
                        - len(frame)
                    ),

                "min_ratio_threshold":
                    MIN_RATIO_THRESHOLD,

                "data_scope":
                    "entire_data",

                "filter_rule": (
                    "selected "
                    "topK_min_time_ratio "
                    f"> {MIN_RATIO_THRESHOLD:.2f} "
                    "independently for each "
                    "scheme side"
                ),
            }
        )

    return pd.DataFrame(rows)


# ============================================================================
# Shared Scheme 1 / Scheme 3 failures
# ============================================================================

def build_shared_failure_summary(
    sheet_frames: dict[str, pd.DataFrame],
) -> tuple[
    pd.DataFrame,
    dict[str, set[tuple[str, int]]],
]:

    summary_rows = []

    overlap_keys_by_sheet: dict[
        str,
        set[tuple[str, int]],
    ] = {}

    for (
        left_scheme,
        right_scheme,
        sheet_name,
    ) in SHEET_SPECS:

        frame = sheet_frames[
            sheet_name
        ]

        if frame.empty:

            overlap_keys_by_sheet[
                sheet_name
            ] = set()

            summary_rows.append(
                {
                    "sheet_name":
                        sheet_name,

                    "scheme_pair":
                        (
                            f"{left_scheme} + "
                            f"{right_scheme}"
                        ),

                    "total_rows":
                        0,

                    "shared_failure_pairs":
                        0,

                    "highlighted_rows":
                        0,

                    "unique_datasets_with_shared_failures":
                        0,

                    "unique_dataset_k_overlap_cases":
                        0,

                    "top_repeated_overlap_dataset_k_pairs":
                        "",
                }
            )

            continue

        # -----------------------------------------------------
        # A shared failure means the same dataset/K appears
        # under BOTH Scheme 1 and Scheme 3.
        # -----------------------------------------------------

        overlap_groups = (
            frame
            .groupby(
                [
                    "dataset",
                    "k_value",
                ],
                dropna=False,
            )["source_scheme"]
            .nunique()
            .reset_index(
                name="scheme_count"
            )
        )

        overlap_groups = (
            overlap_groups[
                overlap_groups[
                    "scheme_count"
                ] >= 2
            ]
            .copy()
        )

        overlap_keys: set[
            tuple[str, int]
        ] = set()

        for row in (
            overlap_groups
            .itertuples(index=False)
        ):
            try:
                key = (
                    str(row.dataset),
                    int(row.k_value),
                )
            except (
                TypeError,
                ValueError,
            ):
                continue

            overlap_keys.add(key)

        overlap_keys_by_sheet[
            sheet_name
        ] = overlap_keys

        if overlap_keys:

            overlap_mask = frame.apply(
                lambda row: (
                    str(row["dataset"]),
                    int(row["k_value"]),
                ) in overlap_keys,
                axis=1,
            )

            overlap_rows = frame[
                overlap_mask
            ].copy()

            # -------------------------------------------------
            # Number of matched Scheme1/Scheme3 row pairs.
            #
            # If a dataset/K appears multiple times per scheme,
            # use min(count scheme1, count scheme3).
            # -------------------------------------------------

            shared_failure_pairs = int(
                overlap_rows
                .groupby(
                    [
                        "dataset",
                        "k_value",
                    ],
                    dropna=False,
                )["source_scheme"]
                .value_counts()
                .groupby(
                    level=[0, 1]
                )
                .min()
                .sum()
            )

            top_overlap_pairs = (
                overlap_rows
                .groupby(
                    [
                        "dataset",
                        "k_value",
                    ],
                    dropna=False,
                )
                .size()
                .sort_values(
                    ascending=False
                )
                .head(5)
            )

            top_overlap_text = "; ".join(
                (
                    f"{dataset}|"
                    f"k={int(k_value)} "
                    f"({int(count)} rows)"
                )
                for (
                    dataset,
                    k_value,
                ), count
                in top_overlap_pairs.items()
            )

            highlighted_rows = int(
                len(overlap_rows)
            )

            unique_shared_datasets = int(
                overlap_rows[
                    "dataset"
                ].nunique(
                    dropna=False
                )
            )

        else:
            shared_failure_pairs = 0
            top_overlap_text = ""
            highlighted_rows = 0
            unique_shared_datasets = 0

        summary_rows.append(
            {
                "sheet_name":
                    sheet_name,

                "scheme_pair":
                    (
                        f"{left_scheme} + "
                        f"{right_scheme}"
                    ),

                "total_rows":
                    int(len(frame)),

                "shared_failure_pairs":
                    shared_failure_pairs,

                "highlighted_rows":
                    highlighted_rows,

                "unique_datasets_with_shared_failures":
                    unique_shared_datasets,

                "unique_dataset_k_overlap_cases":
                    int(len(overlap_keys)),

                "top_repeated_overlap_dataset_k_pairs":
                    top_overlap_text,
            }
        )

    return (
        pd.DataFrame(summary_rows),
        overlap_keys_by_sheet,
    )


# ============================================================================
# Workbook writing
# ============================================================================

def write_workbook(
    output_path: Path,
    summary_df: pd.DataFrame,
    shared_failure_summary_df: pd.DataFrame,
    sheet_frames: dict[str, pd.DataFrame],
    overlap_keys_by_sheet: dict[
        str,
        set[tuple[str, int]],
    ],
) -> None:

    output_path.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    # ---------------------------------------------------------
    # Write workbook.
    # ---------------------------------------------------------

    with pd.ExcelWriter(
        output_path,
        engine="openpyxl",
    ) as writer:

        summary_df.to_excel(
            writer,
            sheet_name=SUMMARY_SHEET,
            index=False,
        )

        shared_failure_summary_df.to_excel(
            writer,
            sheet_name=(
                SHARED_FAILURE_SUMMARY_SHEET
            ),
            index=False,
        )

        for (
            _,
            _,
            sheet_name,
        ) in SHEET_SPECS:

            sheet_frames[
                sheet_name
            ].to_excel(
                writer,
                sheet_name=sheet_name,
                index=False,
            )

    # ---------------------------------------------------------
    # Formatting + highlighting.
    # ---------------------------------------------------------

    workbook = load_workbook(
        output_path
    )

    for sheet_name in workbook.sheetnames:

        worksheet = workbook[
            sheet_name
        ]

        worksheet.freeze_panes = "A2"

        worksheet.auto_filter.ref = (
            worksheet.dimensions
        )

        autosize_columns(
            worksheet
        )

    # ---------------------------------------------------------
    # Highlight shared Scheme1/Scheme3 dataset/K rows.
    # ---------------------------------------------------------

    for (
        sheet_name,
        overlap_keys,
    ) in overlap_keys_by_sheet.items():

        if not overlap_keys:
            continue

        worksheet = workbook[
            sheet_name
        ]

        headers = [
            cell.value
            for cell in worksheet[1]
        ]

        dataset_idx = (
            headers.index("dataset") + 1
        )

        k_idx = (
            headers.index("k_value") + 1
        )

        for row_idx in range(
            2,
            worksheet.max_row + 1,
        ):

            dataset = worksheet.cell(
                row=row_idx,
                column=dataset_idx,
            ).value

            k_value = worksheet.cell(
                row=row_idx,
                column=k_idx,
            ).value

            try:
                key = (
                    str(dataset),
                    int(k_value),
                )

            except (
                TypeError,
                ValueError,
            ):
                continue

            if key not in overlap_keys:
                continue

            for col_idx in range(
                1,
                worksheet.max_column + 1,
            ):

                worksheet.cell(
                    row=row_idx,
                    column=col_idx,
                ).fill = (
                    SHARED_FAILURE_FILL
                )

    workbook.save(
        output_path
    )

    workbook.close()


# ============================================================================
# Validation
# ============================================================================

def validate_output(
    sheet_frames: dict[str, pd.DataFrame],
    xgb_frames: dict[str, pd.DataFrame],
    split_mode: str,
) -> dict[str, object]:

    actual_sheet_names = list(
        sheet_frames.keys()
    )

    expected_sheet_names = [
        sheet_name
        for _, _, sheet_name
        in SHEET_SPECS
    ]

    if actual_sheet_names != (
        expected_sheet_names
    ):
        raise ValueError(
            "Unexpected mixed sheet names: "
            f"expected={expected_sheet_names}, "
            f"found={actual_sheet_names}"
        )

    validation_rows = []

    for (
        left_scheme,
        right_scheme,
        sheet_name,
    ) in SHEET_SPECS:

        frame = sheet_frames[
            sheet_name
        ]

        # -----------------------------------------------------
        # Column order.
        # -----------------------------------------------------

        if list(frame.columns) != (
            OUTPUT_COLUMNS
        ):
            raise ValueError(
                f"{sheet_name} does not match "
                "the required column order."
            )

        # -----------------------------------------------------
        # Only Scheme 1 + Scheme 3.
        # -----------------------------------------------------

        if not frame["scheme"].isin(
            [
                left_scheme,
                right_scheme,
            ]
        ).all():

            raise ValueError(
                f"{sheet_name} contains rows "
                "outside its allowed scheme pair."
            )

        # -----------------------------------------------------
        # XGB only.
        # -----------------------------------------------------

        if not frame["model"].eq(
            "XGB"
        ).all():

            raise ValueError(
                f"{sheet_name} contains "
                "non-XGB rows."
            )

        # -----------------------------------------------------
        # Correct split only.
        # -----------------------------------------------------

        if not frame["split_mode"].eq(
            split_mode
        ).all():

            raise ValueError(
                f"{sheet_name} contains rows "
                f"outside split_mode={split_mode}."
            )

        # -----------------------------------------------------
        # Entire-data only.
        # -----------------------------------------------------

        if not frame["data_scope"].eq(
            "entire_data"
        ).all():

            raise ValueError(
                f"{sheet_name} contains rows "
                "outside entire_data."
            )

        # -----------------------------------------------------
        # Sorted correctly.
        # -----------------------------------------------------

        sorted_frame = (
            frame
            .sort_values(
                [
                    "dataset",
                    "k_value",
                    "scheme",
                ],
                kind="stable",
            )
            .reset_index(drop=True)
        )

        if not (
            frame
            .reset_index(drop=True)
            .equals(sorted_frame)
        ):
            raise ValueError(
                f"{sheet_name} is not sorted by "
                "dataset, k_value, scheme."
            )

        # -----------------------------------------------------
        # Provenance.
        # -----------------------------------------------------

        if frame[
            "source_scheme"
        ].ne(
            frame["scheme"]
        ).any():

            raise ValueError(
                f"{sheet_name} has inconsistent "
                "source_scheme values."
            )

        if (
            not frame.empty
            and frame[
                "source_rule"
            ].nunique() != 1
        ):
            raise ValueError(
                f"{sheet_name} must have a "
                "single source_rule."
            )

        if (
            not frame.empty
            and frame[
                "source_rule"
            ].iloc[0] != sheet_name
        ):
            raise ValueError(
                f"{sheet_name} contains incorrect "
                "source_rule metadata."
            )

        # -----------------------------------------------------
        # Rebuild expected result.
        # -----------------------------------------------------

        expected_frame = build_sheet(
            xgb_frames[
                left_scheme
            ],
            xgb_frames[
                right_scheme
            ],
            source_rule=sheet_name,
        )

        if not (
            frame
            .reset_index(drop=True)
            .equals(
                expected_frame
                .reset_index(drop=True)
            )
        ):
            raise ValueError(
                f"{sheet_name} does not match "
                "the expected filtered rows."
            )

        # -----------------------------------------------------
        # Validate threshold independently on both sides.
        # -----------------------------------------------------

        left_topk, right_topk = (
            extract_topk_pair(
                sheet_name
            )
        )

        left_ratio_column = (
            f"{left_topk}_min_time_ratio"
        )

        right_ratio_column = (
            f"{right_topk}_min_time_ratio"
        )

        left_rows = (
            frame["scheme"]
            .eq(left_scheme)
        )

        right_rows = (
            frame["scheme"]
            .eq(right_scheme)
        )

        left_ratios = pd.to_numeric(
            frame.loc[
                left_rows,
                left_ratio_column,
            ],
            errors="coerce",
        )

        right_ratios = pd.to_numeric(
            frame.loc[
                right_rows,
                right_ratio_column,
            ],
            errors="coerce",
        )

        if not (
            left_ratios
            > MIN_RATIO_THRESHOLD
        ).all():

            raise ValueError(
                f"{sheet_name} contains "
                f"{left_scheme} rows that do "
                f"not satisfy "
                f"{left_ratio_column} > "
                f"{MIN_RATIO_THRESHOLD}."
            )

        if not (
            right_ratios
            > MIN_RATIO_THRESHOLD
        ).all():

            raise ValueError(
                f"{sheet_name} contains "
                f"{right_scheme} rows that do "
                f"not satisfy "
                f"{right_ratio_column} > "
                f"{MIN_RATIO_THRESHOLD}."
            )

        validation_rows.append(
            {
                "sheet_name":
                    sheet_name,

                "rows":
                    int(len(frame)),

                "left_scheme":
                    left_scheme,

                "right_scheme":
                    right_scheme,

                "left_ratio_column":
                    left_ratio_column,

                "right_ratio_column":
                    right_ratio_column,
            }
        )

    return {
        "sheet_names":
            actual_sheet_names,

        "sheet_counts":
            validation_rows,
    }


# ============================================================================
# Shared-failure highlighting validation
# ============================================================================

def validate_shared_failures(
    output_path: Path,
    sheet_frames: dict[str, pd.DataFrame],
    shared_failure_summary_df: pd.DataFrame,
    overlap_keys_by_sheet: dict[
        str,
        set[tuple[str, int]],
    ],
) -> dict[str, dict[str, int]]:

    workbook = load_workbook(
        output_path
    )

    validation: dict[
        str,
        dict[str, int],
    ] = {}

    try:

        if (
            SHARED_FAILURE_SUMMARY_SHEET
            not in workbook.sheetnames
        ):
            raise ValueError(
                f"Missing "
                f"{SHARED_FAILURE_SUMMARY_SHEET} "
                "sheet in output workbook."
            )

        for row in (
            shared_failure_summary_df
            .itertuples(index=False)
        ):

            sheet_name = row.sheet_name

            worksheet = workbook[
                sheet_name
            ]

            headers = [
                cell.value
                for cell in worksheet[1]
            ]

            dataset_idx = (
                headers.index("dataset") + 1
            )

            k_idx = (
                headers.index("k_value") + 1
            )

            expected_overlap_keys = (
                overlap_keys_by_sheet[
                    sheet_name
                ]
            )

            expected_highlighted_rows = int(
                row.highlighted_rows
            )

            actual_highlighted_rows = 0

            actual_overlap_keys: set[
                tuple[str, int]
            ] = set()

            for row_idx in range(
                2,
                worksheet.max_row + 1,
            ):

                row_is_highlighted = any(
                    (
                        worksheet.cell(
                            row=row_idx,
                            column=col_idx,
                        ).fill.fill_type
                        == SHARED_FAILURE_FILL.fill_type
                    )
                    and
                    (
                        worksheet.cell(
                            row=row_idx,
                            column=col_idx,
                        ).fill.start_color.rgb
                        == SHARED_FAILURE_FILL.start_color.rgb
                    )
                    for col_idx in range(
                        1,
                        worksheet.max_column + 1,
                    )
                )

                dataset = worksheet.cell(
                    row=row_idx,
                    column=dataset_idx,
                ).value

                k_value = worksheet.cell(
                    row=row_idx,
                    column=k_idx,
                ).value

                try:
                    key = (
                        str(dataset),
                        int(k_value),
                    )
                except (
                    TypeError,
                    ValueError,
                ):
                    continue

                should_highlight = (
                    key
                    in expected_overlap_keys
                )

                if (
                    row_is_highlighted
                    != should_highlight
                ):
                    raise ValueError(
                        f"{sheet_name} has "
                        "incorrect shared-failure "
                        f"highlighting for {key}."
                    )

                if row_is_highlighted:
                    actual_highlighted_rows += 1
                    actual_overlap_keys.add(
                        key
                    )

            if (
                actual_highlighted_rows
                != expected_highlighted_rows
            ):
                raise ValueError(
                    f"{sheet_name} highlighted "
                    "row count mismatch: "
                    f"expected "
                    f"{expected_highlighted_rows}, "
                    f"found "
                    f"{actual_highlighted_rows}."
                )

            if (
                actual_overlap_keys
                != expected_overlap_keys
            ):
                raise ValueError(
                    f"{sheet_name} overlap-key "
                    "mismatch in workbook "
                    "highlighting."
                )

            validation[
                sheet_name
            ] = {
                "total_rows":
                    int(
                        len(
                            sheet_frames[
                                sheet_name
                            ]
                        )
                    ),

                "shared_failure_pairs":
                    int(
                        row.shared_failure_pairs
                    ),

                "highlighted_rows":
                    actual_highlighted_rows,

                "unique_datasets_with_shared_failures":
                    int(
                        row.unique_datasets_with_shared_failures
                    ),

                "unique_dataset_k_overlap_cases":
                    int(
                        row.unique_dataset_k_overlap_cases
                    ),
            }

    finally:
        workbook.close()

    return validation


