"""Build Scheme 1 vs Scheme 3 XGB mixed failure-case combinations.

This script consumes the current enriched failure-analysis workbook produced by
failure_analysis_summary.py.

It supports exactly one split mode per invocation:

    strat_y
    strat_y_K

Run the script twice to produce two independent workbooks.

Only:
    - Scheme 1
    - Scheme 3
    - XGB
    - entire_data important failures

are used.

For each top-k pairing, rows are retained when the selected
topK_min_time_ratio > MIN_RATIO_THRESHOLD.

Rows sharing the same (dataset, k_value) across Scheme 1 and Scheme 3 are
highlighted yellow.
"""

